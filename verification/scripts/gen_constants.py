"""Check that lanehash's constant table `C` is the fractional hex digits of pi, and write
it as Lean data (verification/lean/Lanehash/Constants.lean).

Pi comes from Machin's formula in exact integer arithmetic, independent of the Rust
source. The table is parsed from lanehash/src/constants.rs."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "lanehash/src/constants.rs").read_text()
body = src[src.index("pub const C:"):]
body = body[:body.index("];\n") + 2]
groups = re.findall(r"\[((?:\s*0x[0-9a-f]{2},?)+)\]", body)
C = [[int(x, 16) for x in g.replace(",", " ").split()] for g in groups]
assert len(C) == 56 and all(len(g) == 16 for g in C), (len(C))

def arctan_inv(x, one):
    # arctan(1/x) * one by the alternating series, exact integers
    total, term, k, sign = 0, one // x, 1, 1
    x2 = x * x
    while term:
        total += sign * (term // k)
        term //= x2
        k += 2
        sign = -sign
    return total

bits = 8 * 56 * 16 + 64
one = 1 << bits
pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))
frac = pi - 3 * one
digits = frac >> 64  # drop the guard bits
flat = digits.to_bytes(56 * 16, "big")
pi_ok = [list(flat[16 * i:16 * i + 16]) for i in range(56)] == C
print("C is the fractional hex digits of pi:", pi_ok)

out = root / "verification/lean/Lanehash/Constants.lean"
rows = ",\n  ".join("#[" + ", ".join(str(b) for b in g) + "]" for g in C)
out.write_text(
    "/-! The constant table `C` of `lanehash/src/constants.rs`, generated by\n"
    "`verification/scripts/gen_constants.py`, which also checks that it is the fractional\n"
    "hex digits of pi. Each group is 16 bytes. -/\n\n"
    "namespace Lanehash\n\n"
    "def C : Array (Array Nat) := #[\n  " + rows + "]\n\n"
    "end Lanehash\n")
print("wrote", out.relative_to(root))
sys.exit(0 if pi_ok else 1)
